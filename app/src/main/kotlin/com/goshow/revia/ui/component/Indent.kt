package com.goshow.revia.ui.component

import androidx.compose.ui.unit.Dp
import com.goshow.revia.ui.theme.Dimen

/**
 * 一覧の行の字下げ。**1 段ごとに [step] ずつ下げ、[maxLevel] より深い段は増やさない**（決定 10）。
 *
 * ## なぜ上限があるのか
 *
 * 項目は `parent_id` の**可変ツリー**で持ち、**データ側に段数の制限を入れていない**（決定 10）。
 * 教材によって `章→節→問題` だったり `章→節→小節→問題` だったりして、深さを先に決められないためである。
 * つまり **上限より深い教材は実際に作れる**。字下げを段数のぶんだけ増やし続けると、
 * 深い教材で行の文字が右へ押し出される。基準の画面幅は 360dp で、
 * 左右の [Dimen.ScreenPadding] を引くと残りは 324dp しかない。
 *
 * 打ち切っても構造は失われない。**段の深さは字下げだけでなく、行の並び順と親子関係でも読める**。
 * 深さの問題を表示の問題として表示で解く、というのが決定 10 の主旨である。
 *
 * ## なぜ計算を 1 か所に置くのか
 *
 * この規則を使う画面は 2 つある。画面 6（読み取り結果の確認）と画面 8（教材詳細）である。
 * 両者は**行そのものを共有しない**（#34）。6 は編集用（取っ手・要確認・改名）、8 は記録用で、
 * 押したときに起きることが違うためである。共有するのは**この計算と [MarkState] だけ**である。
 *
 * 上限が片方の画面にしか入っていないと、**同じ項目が画面 6 と画面 8 で違う位置に出る**。
 * 取り込んだ直後に確認した並びと、あとで開いたときの並びが食い違うので、
 * 利用者からは「読み取りが間違っている」か「勝手に構造が変わった」ように見える。
 * どちらも実際には起きていないので、直しようがない。
 *
 * ## なぜ [step] と [maxLevel] を引数で受けるのか
 *
 * 既定は [Dimen] の値だが、**関数の中で [Dimen] を直接読まない**。
 * テストから設計と違う値（上限 0、上限 1、刻み 0dp）を入れて、
 * **数字ではなく規則そのものが保たれているか**を確かめられるようにするためである。
 * [indicatorOffsetFor] と同じ手口。
 *
 * @param level 段の深さ。0 が最上段（章）。**負でも落ちず 0 に倒す**。
 *   ツリーの編集中に段を上げすぎた途中の値が来たとき、画面が落ちるより 0dp に倒すほうが直せる
 * @param step 1 段ぶんの字下げ
 * @param maxLevel 字下げを増やす上限の段。これより深い段は [maxLevel] と同じ字下げになる。
 *   負のときは 0 として扱う（どの段も字下げしない）
 * @return 行の左に空ける幅。[level] が 0 以下なら 0dp
 */
internal fun indentFor(
    level: Int,
    step: Dp = Dimen.IndentStep,
    maxLevel: Int = Dimen.MaxIndentLevel,
): Dp {
    // 内側の coerceAtLeast は、上限が負のときに coerceIn(0, 負) が落ちるのを防ぐためのもの。
    // 引数で受ける以上、設計外の値が来ても規則（深いほど広く、上限で止まる）を壊さずに畳む
    val capped = level.coerceIn(0, maxLevel.coerceAtLeast(0))
    return step * capped
}
